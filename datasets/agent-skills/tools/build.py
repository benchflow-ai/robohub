#!/usr/bin/env python3
"""Build the agent-skills bench tasks from their sources.

    python3 tools/build.py            # writes tasks/with-skill/<id>/ and tasks/no-skill/<id>/ for every src/<id>/

Each src/<id>/ holds one task:
    task.yaml      id, source (a key of sources.yaml), skill, scenario, difficulty, timeout_sec, optional protect/allow
    prompt.md      the request the agent gets (the shared preamble is added here)
    setup/         files/ copied over the repository, then setup.sh (optional) run in its root: the starting state
    solution/      files/ copied over the repository, then solve.sh (optional): the reference solution
    tests/         hidden pytest files the verifier runs (plus src/_shared/tests/<source>/*.py helpers, copied next to them)
    trivial/       N.sh: shortcut edits that must fail (used by tools/check.py only, not published in the task)
    valid/         N.sh: optional alternative correct solutions that must pass (tools/check.py only, not published)

The two variants differ in one step: no-skill runs environment/variant.sh, which deletes the source's guide_files
(sources.yaml) before the workspace is committed; with-skill keeps the repository as shipped. Everything else,
including the prompt and the verifier, is byte-identical. Needs only the Python standard library and PyYAML.
"""
import shutil
import stat
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
VARIANTS = ("with-skill", "no-skill")

PREAMBLE = """You are working in a checkout of {name} ({repo}, commit {short}) at `{workdir}`. It is a git repository with one commit, so `git diff` shows your changes.

The Python environment is already set up: run `python` (Python 3.12 with CPU-only PyTorch{env_note}). There is no GPU{sim_note}. Do not install or upgrade packages{lib_rule}. Leave your changes in the working tree; you do not need to commit them.

Do not stop to ask questions: there is nobody to answer. Make reasonable assumptions, do the work, and check it as far as this machine allows.

## Request

"""

ENV_NOTES = {
    "isaaclab": (", Isaac Lab installed from this checkout in editable mode, and NVIDIA Warp in CPU mode",
                 " and no Isaac Sim, so you cannot launch a simulation app or step an environment; you can import Isaac Lab modules, build configs and call functions on CPU tensors"),
    "lerobot": (", LeRobot installed from this checkout in editable mode", " and no robot hardware"),
    "genesis": (", Genesis installed from this checkout in editable mode", "; use the Genesis CPU backend (`gs.init(backend=gs.cpu)`)"),
}

INSTALL = {
    "isaaclab": "for p in isaaclab isaaclab_assets isaaclab_contrib isaaclab_experimental isaaclab_newton isaaclab_ov "
                "isaaclab_physx isaaclab_rl isaaclab_tasks isaaclab_tasks_experimental isaaclab_visualizers; do "
                "pip install --no-cache-dir --no-deps --no-build-isolation -e source/$p || exit 1; done",
    "lerobot": "pip install --no-cache-dir --no-deps --no-build-isolation -e .",
    "genesis": "pip install --no-cache-dir --no-deps --no-build-isolation -e .",
}

APT = {"isaaclab": "", "lerobot": " ffmpeg", "genesis": " libgl1 libegl1 libglib2.0-0"}

DOCKERFILE = """# Agent-skills task {id}, variant {variant}. Generated by datasets/agent-skills/tools/build.py from src/{id}/; edit the source, not this file.
# {name} at commit {commit} ({licence}, {repo}), fetched at build time without its git history.
FROM python:3.12-slim-bookworm
# curl, xz-utils and ca-certificates let BenchFlow install the agent harnesses (Claude Code, Codex) at run time.
RUN apt-get update \\
 && apt-get install -y --no-install-recommends git curl ca-certificates xz-utils ripgrep build-essential{apt} \\
 && rm -rf /var/lib/apt/lists/*
COPY requirements.txt /opt/skills-study/requirements.txt
# requirements.txt pins every package, torch as its CPU-only build (+cpu) from the PyTorch index.
RUN pip install --no-cache-dir --extra-index-url https://download.pytorch.org/whl/cpu -r /opt/skills-study/requirements.txt
RUN git init -q {workdir} && cd {workdir} \\
 && git fetch -q --depth 1 {repo}.git {commit} && git checkout -q FETCH_HEAD && rm -rf .git
RUN cd {workdir} && {install}
COPY setup/ /opt/skills-study/setup/
COPY variant.sh integrity.py /opt/skills-study/
# Starting state, then the variant step (no-skill deletes the guide files; with-skill changes nothing), then the
# integrity manifest of the protected upstream files and a fresh one-commit git repository, whose commit id is kept for the verifier (both root-only).
RUN cd {workdir} && sh /opt/skills-study/setup/apply.sh && rm -rf /opt/skills-study/setup \\
 && sh /opt/skills-study/variant.sh \\
 && python3 /opt/skills-study/integrity.py write {protect} > /opt/skills-study/protected.sha256 \\
 && chmod -R go-rwx /opt/skills-study \\
 && git init -q && git add -A \\
 && git -c user.name=workspace -c user.email=workspace@localhost commit -qm "Workspace" \\
 && git rev-parse HEAD > /opt/skills-study/base_commit \\
 && mkdir -p /logs/verifier /logs/agent /logs/artifacts
ENV PYTHONUNBUFFERED=1
WORKDIR {workdir}
"""

APPLY = """#!/bin/sh
# Applies the task's starting state in the repository root (run by the Dockerfile and by tools/check.py).
set -eu
D="$(cd "$(dirname "$0")" && pwd)"
if [ -d "$D/files" ]; then cp -a "$D/files/." .; fi
if [ -f "$D/setup.sh" ]; then sh "$D/setup.sh"; fi
"""

SOLVE = """#!/bin/bash
# Reference solution: copies the solution files over the repository, then runs solution/solve.sh if present.
# BenchFlow uploads /oracle only in oracle mode; agents never see it.
set -euo pipefail
O="$(cd "$(dirname "$0")" && pwd)"
cd "${{SKILLS_STUDY_WORKDIR:-{workdir}}}"
if [ -d "$O/solution/files" ]; then cp -a "$O/solution/files/." .; fi
if [ -f "$O/solution/solve.sh" ]; then bash "$O/solution/solve.sh"; fi
"""

TEST_SH = """#!/bin/bash
# Deterministic verifier: (1) protected upstream files are unchanged, (2) the hidden tests pass. Reward 1 or 0.
# The tests run from this directory with `python -I`, so nothing the agent put in the workspace can shadow pytest.
set -u
V="$(cd "$(dirname "$0")" && pwd)"
W="${{SKILLS_STUDY_WORKDIR:-{workdir}}}"
S="${{SKILLS_STUDY_DIR:-/opt/skills-study}}"
mkdir -p /logs/verifier
reward() {{ echo "$1" > /logs/verifier/reward.txt; echo "reward $1"; exit 0; }}
cd "$W" || reward 0
if ! python3 "$S/integrity.py" check "$S/protected.sha256"; then echo "FAIL: protected upstream files were changed"; reward 0; fi
cd "$V"
SKILLS_STUDY_WORKDIR="$W" timeout {test_timeout} python3 -I -m pytest -q -p no:cacheprovider -c "$V/pytest.ini" --rootdir "$V" "$V/tests" 2>&1 | tee /logs/verifier/pytest.txt
if [ "${{PIPESTATUS[0]}}" = 0 ]; then reward 1; else reward 0; fi
"""

PYTEST_INI = """[pytest]
addopts = -p no:cacheprovider
filterwarnings =
    ignore::DeprecationWarning:warp.*
"""


def variant_script(src, variant):
    lines = ["#!/bin/sh", f"# Variant {variant}: " + ("deletes the agent-facing guide files of " + src["name"] + "." if variant == "no-skill"
                                                    else "keeps the repository as shipped (nothing to do)."), "set -eu"]
    if variant == "no-skill":
        plain = [g for g in src["guide_files"] if not g.startswith("**/")]
        named = [g[3:] for g in src["guide_files"] if g.startswith("**/")]
        if plain:
            lines.append("rm -rf " + " ".join(plain))
        if named:
            expr = " -o ".join(f"-name {n}" for n in named)
            lines.append(f"find . \\( {expr} \\) -exec rm -rf {{}} +")
        # Fail the build if anything is left, so a variant can never ship a guide file by accident.
        checks = " ".join(plain)
        if checks:
            lines.append(f"for p in {checks}; do if [ -e \"$p\" ] || [ -L \"$p\" ]; then echo \"left: $p\"; exit 1; fi; done")
        if named:
            expr = " -o ".join(f"-name {n}" for n in named)
            lines.append(f"if [ -n \"$(find . \\( {expr} \\) -print -quit)\" ]; then echo 'guide file left'; exit 1; fi")
    return "\n".join(lines) + "\n"


def chmod_x(p):
    p.chmod(p.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def frontmatter(t, src, variant):
    return {
        "schema_version": "1.3",
        "task": {"name": f"agent-skills/{t['id']}", "description": t["summary"]},
        "metadata": {
            "author_name": "benchflow",
            "source_repo": src["repo"],
            "source_commit": src["commit"],
            "source_licence": src["licence"],
            "skill": t["skill"],
            "scenario": t["scenario"],
            "variant": variant,
            "suite": "agent-skills",
            "category": t.get("category", "coding"),
            "difficulty": t.get("difficulty", "medium"),
            "tags": ["agent-skills", t["source"], variant] + t.get("tags", []),
            "gpu": "none",
        },
        "agent": {"timeout_sec": t.get("timeout_sec", 1800)},
        "verifier": {"timeout_sec": t.get("verifier_timeout_sec", 600)},
        "sandbox": {"cpus": t.get("cpus", 2), "memory_mb": t.get("memory_mb", 4096), "build_timeout_sec": 3600},
    }


def build_task(tdir, sources, out_root):
    t = yaml.safe_load((tdir / "task.yaml").read_text())
    assert t["id"] == tdir.name, f"{tdir}: id {t['id']} != folder name"
    src = sources[t["source"]]
    env_note, sim_note = ENV_NOTES[t["source"]]
    protect = [p for p in src["protect"] + t.get("protect", []) if p not in t.get("allow", [])]
    prompt = PREAMBLE.format(name=src["name"], repo=src["repo"], short=src["commit"][:12], workdir=src["workdir"],
                             env_note=env_note, sim_note=sim_note,
                             lib_rule="" if t.get("library_task") else f", and do not edit {src['name']}'s own library code") + (tdir / "prompt.md").read_text().strip() + "\n"
    for variant in VARIANTS:
        out = out_root / variant / t["id"]
        if out.exists():
            shutil.rmtree(out)
        env = out / "environment"
        (env / "setup").mkdir(parents=True)
        # shared: [{from: _shared/..., to: path in the repository}] copies a starting project several tasks share.
        for sh in t.get("shared", []):
            shutil.copytree(ROOT / "src" / sh["from"], env / "setup" / "files" / sh["to"], dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns("__pycache__"))
        if (tdir / "setup").is_dir():
            shutil.copytree(tdir / "setup", env / "setup", dirs_exist_ok=True)
        (env / "setup" / "apply.sh").write_text(APPLY)
        shutil.copy(ROOT / "env" / t["source"] / "requirements.txt", env / "requirements.txt")
        shutil.copy(ROOT / "tools" / "integrity.py", env / "integrity.py")
        (env / "variant.sh").write_text(variant_script(src, variant))
        (env / "Dockerfile").write_text(DOCKERFILE.format(
            id=t["id"], variant=variant, name=src["name"], commit=src["commit"], licence=src["licence"], repo=src["repo"],
            workdir=src["workdir"], apt=APT[t["source"]], install=INSTALL[t["source"]],
            protect=" ".join(protect) or "."))
        orc = out / "oracle"
        orc.mkdir()
        shutil.copytree(tdir / "solution", orc / "solution")
        (orc / "solve.sh").write_text(SOLVE.format(workdir=src["workdir"]))
        chmod_x(orc / "solve.sh")
        ver = out / "verifier"
        ver.mkdir()
        shutil.copytree(tdir / "tests", ver / "tests", ignore=shutil.ignore_patterns("__pycache__"))
        helpers = ROOT / "src" / "_shared" / "tests" / t["source"]
        if helpers.is_dir():
            shutil.copytree(helpers, ver / "tests", dirs_exist_ok=True, ignore=shutil.ignore_patterns("__pycache__"))
        (ver / "pytest.ini").write_text(PYTEST_INI)
        (ver / "test.sh").write_text(TEST_SH.format(workdir=src["workdir"], test_timeout=t.get("test_timeout_sec", 480)))
        chmod_x(ver / "test.sh")
        fm = yaml.safe_dump(frontmatter(t, src, variant), sort_keys=False, allow_unicode=True, width=1000)
        (out / "task.md").write_text(f"---\n{fm}---\n\n{prompt}")
    return t


def main():
    sources = yaml.safe_load((ROOT / "sources.yaml").read_text())
    only = set(sys.argv[1:])
    out_root = ROOT / "tasks"
    built = []
    for tdir in sorted((ROOT / "src").iterdir()):
        if tdir.is_dir() and (tdir / "task.yaml").exists() and (not only or tdir.name in only):
            built.append(build_task(tdir, sources, out_root))
    if not only:  # drop tasks whose source folder is gone
        names = {t["id"] for t in built}
        for variant in VARIANTS:
            for d in sorted((out_root / variant).glob("*")) if (out_root / variant).exists() else []:
                if d.name not in names:
                    shutil.rmtree(d)
    print(f"built {len(built)} tasks x {len(VARIANTS)} variants")


if __name__ == "__main__":
    main()
